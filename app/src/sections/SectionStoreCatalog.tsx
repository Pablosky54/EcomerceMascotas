    setFilterState(prev => {
      const newState = { ...prev, ...updates };

      // Reset price range when changing pet type
      if (updates.petType && updates.petType !== prev.petType) {
        const typedPets = petsData.filter(p => p.type === updates.petType);
        const minPrice = Math.min(...typedPets.map(p => p.price));
        const maxPrice = Math.max(...typedPets.map(p => p.price));
        newState.priceRange = [minPrice, maxPrice];
      }

      return newState;
    });
